import asyncio
from playwright.async_api import async_playwright
D="/tmp/browser/t/"
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(headless=True,args=["--autoplay-policy=no-user-gesture-required"]); pg=await b.new_page(viewport={"width":390,"height":844})
    errs=[]; pg.on("pageerror",lambda e:errs.append(str(e))); pg.on("console",lambda m: m.type=="error" and errs.append(m.text))
    await pg.goto("http://localhost:8080"); await pg.wait_for_timeout(2500)
    await pg.get_by_role("button",name="New Alarm").last.click()
    await pg.fill("#rel-minutes","1")
    await pg.set_input_files("#ringtone-file",D+"tone.wav")
    await pg.set_input_files("#image-file",D+"wide.png"); await pg.wait_for_timeout(500)
    await pg.get_by_role("button",name="Preview ringtone").click(); await pg.wait_for_timeout(300)
    await pg.get_by_role("button",name="Stop preview").click()
    await pg.locator("#image-file").scroll_into_view_if_needed()
    await pg.screenshot(path=D+"a1.png")
    await pg.get_by_role("button",name="Create alarm").click(); await pg.wait_for_timeout(800)
    await pg.screenshot(path=D+"a2.png")
    await pg.evaluate("""()=>{const k='timenest.alarms.v1';const a=JSON.parse(localStorage.getItem(k));a.forEach(x=>{x.enabled=x.imageId?true:false; if(x.imageId)x.targetAt=Date.now()-1000});localStorage.setItem(k,JSON.stringify(a))}""")
    await pg.reload(); await pg.wait_for_timeout(2500)
    playing=await pg.evaluate("()=>1")
    await pg.screenshot(path=D+"a3.png")
    await pg.get_by_role("button",name="Stop").click(); await pg.wait_for_timeout(500)
    await pg.get_by_role("button",name="Edit alarm").first.click(); await pg.wait_for_timeout(800)
    print("edit shows:", await pg.locator("text=tone.wav").count(), await pg.locator("text=wide.png").count())
    await pg.keyboard.press("Escape"); await pg.wait_for_timeout(400)
    await pg.get_by_role("button",name="Appearance settings").click(); await pg.wait_for_timeout(400)
    await pg.get_by_role("radio",name="Light").click()
    await pg.set_input_files("#bg-file",D+"bg.jpg"); await pg.wait_for_timeout(800)
    await pg.screenshot(path=D+"a4.png")
    await pg.keyboard.press("Escape"); await pg.reload(); await pg.wait_for_timeout(2500)
    await pg.screenshot(path=D+"a5.png")
    print(errs); await b.close()
asyncio.run(main())
